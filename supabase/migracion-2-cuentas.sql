begin;

-- ---------- Arancel y W.O. ----------

alter table public.configuracion
  add column arancel integer not null default 105000 check (arancel between 0 and 10000000);

-- Equipo que no se presentó: el otro gana 3 a 0
alter table public.partidos
  add column ausente text check (ausente in ('local', 'visitante')),
  add constraint partidos_wo_check check (
    ausente is null
    or (not postergado and (
      (ausente = 'visitante' and goles_local = 3 and goles_visitante = 0)
      or (ausente = 'local' and goles_local = 0 and goles_visitante = 3)
    ))
  );

-- ---------- Tablas privadas nuevas (solo admins) ----------

-- Amarillas: solo registro (las rojas son las expulsiones)
create table public.tarjetas (
  id bigint generated by default as identity primary key,
  partido_id bigint not null references public.partidos (id),
  equipo_id bigint not null references public.equipos (id),
  numero_camiseta smallint not null check (numero_camiseta between 1 and 99),
  nombre_jugador text not null default '' check (char_length(nombre_jugador) <= 60),
  creado_en timestamptz not null default now()
);
create index tarjetas_partido_idx on public.tarjetas (partido_id);

-- Cuenta corriente: pagos (de un partido o sueltos) y deudas anteriores
create table public.movimientos (
  id bigint generated by default as identity primary key,
  equipo_id bigint not null references public.equipos (id),
  partido_id bigint references public.partidos (id),
  tipo text not null check (tipo in ('pago', 'deuda_anterior')),
  monto integer not null check (monto between 1 and 10000000),
  metodo text check (metodo in ('efectivo', 'transferencia')),
  fecha date not null,
  nota text not null default '' check (char_length(nota) <= 100),
  creado_en timestamptz not null default now(),
  check ((tipo = 'pago') = (metodo is not null)),
  check (tipo = 'pago' or partido_id is null)
);
create index movimientos_equipo_idx on public.movimientos (equipo_id);
-- Un solo pago por equipo en cada partido
create unique index movimientos_pago_partido_idx on public.movimientos (partido_id, equipo_id)
  where partido_id is not null;

-- ---------- Reglas que valen para cualquiera que escriba ----------

create function public.validar_tarjeta() returns trigger
language plpgsql set search_path = '' as $$
begin
  if not exists (
    select 1 from public.partidos p
    where p.id = new.partido_id and new.equipo_id in (p.local_id, p.visitante_id)
  ) then
    raise exception 'El equipo de la tarjeta no jugó ese partido';
  end if;
  return new;
end;
$$;

create trigger tarjetas_validar
before insert or update on public.tarjetas
for each row execute function public.validar_tarjeta();

-- El pago de un partido es de uno de sus equipos, y no del que no se presentó
create function public.validar_movimiento() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.partido_id is not null and not exists (
    select 1 from public.partidos p
    where p.id = new.partido_id
      and ((new.equipo_id = p.local_id and p.ausente is distinct from 'local')
        or (new.equipo_id = p.visitante_id and p.ausente is distinct from 'visitante'))
  ) then
    raise exception 'El pago tiene que ser de un equipo que jugó ese partido';
  end if;
  return new;
end;
$$;

create trigger movimientos_validar
before insert or update on public.movimientos
for each row execute function public.validar_movimiento();

-- ---------- Permisos y reglas de acceso (RLS) ----------

revoke all on public.tarjetas, public.movimientos from anon, authenticated;
grant select, insert, update, delete on public.tarjetas, public.movimientos to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.tarjetas enable row level security;
alter table public.movimientos enable row level security;
create policy "Solo admins" on public.tarjetas for all to authenticated
  using ((select public.es_admin())) with check ((select public.es_admin()));
create policy "Solo admins" on public.movimientos for all to authenticated
  using ((select public.es_admin())) with check ((select public.es_admin()));

commit;
