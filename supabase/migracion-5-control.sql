begin;

-- ---------- Roles ----------

-- admin: el panel de siempre. superadmin: además ve el registro de actividad.
alter table public.administradores
  add column rol text not null default 'admin' check (rol in ('admin', 'superadmin'));

create function public.es_superadmin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.administradores where user_id = (select auth.uid()) and rol = 'superadmin'
  );
$$;
grant execute on function public.es_superadmin() to authenticated;

-- ---------- Registro de actividad ----------

-- Qué se hizo (sin el valor anterior): la fila como quedó (o como estaba, si se borró)
-- y, en un cambio, qué columnas cambiaron
create table public.actividad (
  id bigint generated by default as identity primary key,
  creado_en timestamptz not null default now(),
  user_id uuid references auth.users (id) on delete set null,
  quien text not null,
  accion text not null check (accion in ('alta', 'cambio', 'baja')),
  tabla text not null,
  fila jsonb,
  cambios text[]
);
create index actividad_creado_en_idx on public.actividad (creado_en);

-- La anota la base en cada alta, cambio o baja, también desde el SQL Editor (sin cuenta)
create function public.registrar_actividad() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  cambios text[];
begin
  if tg_op = 'UPDATE' then
    select array_agg(nuevo.key order by nuevo.key) into cambios
    from jsonb_each(to_jsonb(new)) as nuevo
    where nuevo.value is distinct from to_jsonb(old) -> nuevo.key;
    if cambios is null then
      return null;
    end if;
  end if;
  insert into public.actividad (user_id, quien, accion, tabla, fila, cambios)
  values (
    (select auth.uid()),
    coalesce((select a.nombre from public.administradores a where a.user_id = (select auth.uid())), 'Supabase (SQL)'),
    case tg_op when 'INSERT' then 'alta' when 'UPDATE' then 'cambio' else 'baja' end,
    tg_table_name,
    case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end,
    cambios
  );
  return null;
end;
$$;

do $$
declare
  tabla text;
begin
  foreach tabla in array array['partidos', 'tarjetas', 'expulsiones', 'movimientos', 'equipos', 'delegados', 'configuracion'] loop
    execute format(
      'create trigger %I after insert or update or delete on public.%I '
      'for each row execute function public.registrar_actividad()', tabla || '_actividad', tabla);
  end loop;
end;
$$;

-- Solo el superadmin lo lee; nadie lo escribe ni lo borra desde la app (solo el trigger)
revoke all on public.actividad from anon, authenticated;
grant select on public.actividad to authenticated;
alter table public.actividad enable row level security;
create policy "Solo el superadmin" on public.actividad
  for select to authenticated using ((select public.es_superadmin()));

