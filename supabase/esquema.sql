-- ---------- Tablas públicas ----------

create table public.categorias (
  id smallint primary key,
  nombre text not null unique,
  orden smallint not null
);

create table public.zonas (
  id smallint primary key,
  categoria_id smallint not null references public.categorias (id),
  nombre text not null,
  unique (categoria_id, nombre)
);

create table public.equipos (
  id bigint generated by default as identity primary key,
  zona_id smallint not null references public.zonas (id),
  nombre text not null check (char_length(btrim(nombre)) between 1 and 60)
);
create index equipos_zona_idx on public.equipos (zona_id);

-- Con lo que arrancó cada equipo: la fecha 1 se cargó sin el detalle de los partidos
create table public.tabla_inicial (
  equipo_id bigint primary key references public.equipos (id) on delete cascade,
  pj smallint not null default 0 check (pj >= 0),
  pg smallint not null default 0 check (pg >= 0),
  pe smallint not null default 0 check (pe >= 0),
  pp smallint not null default 0 check (pp >= 0),
  gf smallint not null default 0 check (gf >= 0),
  gc smallint not null default 0 check (gc >= 0),
  check (pg + pe + pp = pj)
);

-- Partidos de una categoría: en las zonas impares se cruzan equipos de zonas distintas
create table public.partidos (
  id bigint generated by default as identity primary key,
  categoria_id smallint not null references public.categorias (id),
  fecha smallint not null check (fecha between 1 and 60),
  local_id bigint not null references public.equipos (id),
  visitante_id bigint not null references public.equipos (id),
  goles_local smallint check (goles_local between 0 and 99),
  goles_visitante smallint check (goles_visitante between 0 and 99),
  postergado boolean not null default false,
  check (local_id <> visitante_id),
  check ((goles_local is null) = (goles_visitante is null)),
  check (not (postergado and goles_local is not null))
);
create index partidos_categoria_fecha_idx on public.partidos (categoria_id, fecha);

create table public.configuracion (
  id smallint primary key default 1 check (id = 1),
  nombre_campeonato text not null check (char_length(btrim(nombre_campeonato)) between 1 and 60),
  criterios_desempate text[] not null check (
    cardinality(criterios_desempate) = 4
    and criterios_desempate <@ array['puntos', 'dg', 'gf', 'enfrentamiento']::text[]
  )
);

-- ---------- Tablas privadas (solo admins) ----------

create table public.delegados (
  equipo_id bigint primary key references public.equipos (id) on delete cascade,
  nombre text not null default '' check (char_length(nombre) <= 60),
  telefono text not null default '' check (telefono = '' or telefono ~ '^[0-9]{10,15}$')
);

create table public.expulsiones (
  id bigint generated by default as identity primary key,
  partido_id bigint not null references public.partidos (id),
  equipo_id bigint not null references public.equipos (id),
  numero_camiseta smallint not null check (numero_camiseta between 1 and 99),
  nombre_jugador text not null default '' check (char_length(nombre_jugador) <= 60),
  fechas_suspension smallint check (fechas_suspension between 0 and 99),
  fechas_cumplidas smallint not null default 0 check (fechas_cumplidas between 0 and 99),
  creado_en timestamptz not null default now(),
  check (fechas_suspension is null or fechas_cumplidas <= fechas_suspension)
);
create index expulsiones_partido_idx on public.expulsiones (partido_id);

create table public.administradores (
  user_id uuid primary key references auth.users (id) on delete cascade,
  nombre text not null default ''
);

-- ---------- Reglas que valen para cualquiera que escriba ----------

create function public.validar_partido() returns trigger
language plpgsql set search_path = '' as $$
begin
  if exists (
    select 1
    from public.equipos e
    join public.zonas z on z.id = e.zona_id
    where e.id in (new.local_id, new.visitante_id)
      and z.categoria_id <> new.categoria_id
  ) then
    raise exception 'Los dos equipos tienen que ser de la categoría del partido';
  end if;
  return new;
end;
$$;

create trigger partidos_validar
before insert or update on public.partidos
for each row execute function public.validar_partido();

create function public.validar_expulsion() returns trigger
language plpgsql set search_path = '' as $$
begin
  if not exists (
    select 1 from public.partidos p
    where p.id = new.partido_id and new.equipo_id in (p.local_id, p.visitante_id)
  ) then
    raise exception 'El equipo de la expulsión no jugó ese partido';
  end if;
  return new;
end;
$$;

create trigger expulsiones_validar
before insert or update on public.expulsiones
for each row execute function public.validar_expulsion();

-- ¿Quien hace la consulta es admin? (security definer: puede leer administradores)
create function public.es_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.administradores where user_id = (select auth.uid()));
$$;

-- ---------- Permisos ----------

revoke all on all tables in schema public from anon, authenticated;
grant usage on schema public to anon, authenticated;

grant select on public.categorias, public.zonas, public.equipos, public.tabla_inicial,
  public.partidos, public.configuracion to anon, authenticated;
grant insert, update, delete on public.categorias, public.zonas, public.equipos,
  public.tabla_inicial, public.partidos, public.configuracion to authenticated;
grant select, insert, update, delete on public.delegados, public.expulsiones to authenticated;
grant select on public.administradores to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.es_admin() to anon, authenticated;

-- ---------- Reglas de acceso (RLS) ----------

do $$
declare
  tabla text;
begin
  -- Lo público lo lee cualquiera; solo los admins lo modifican
  foreach tabla in array array['categorias', 'zonas', 'equipos', 'tabla_inicial', 'partidos', 'configuracion'] loop
    execute format('alter table public.%I enable row level security', tabla);
    execute format('create policy "Lectura pública" on public.%I for select to anon, authenticated using (true)', tabla);
    execute format(
      'create policy "Solo admins modifican" on public.%I for all to authenticated '
      'using ((select public.es_admin())) with check ((select public.es_admin()))', tabla);
  end loop;
  -- Lo privado: solo admins, para todo
  foreach tabla in array array['delegados', 'expulsiones'] loop
    execute format('alter table public.%I enable row level security', tabla);
    execute format(
      'create policy "Solo admins" on public.%I for all to authenticated '
      'using ((select public.es_admin())) with check ((select public.es_admin()))', tabla);
  end loop;
end;
$$;

alter table public.administradores enable row level security;
create policy "Cada admin ve su fila" on public.administradores
  for select to authenticated using (user_id = (select auth.uid()));
